using System.Diagnostics;
using System.Globalization;
using System.IO.Compression;
using System.Net;
using System.Text;
using System.Text.Json;
using JustCryptDns.Core.Configuration;
using JustCryptDns.Core.Interfaces;
using JustCryptDns.Core.Models;
using JustCryptDns.DNS.Resolver;
using Microsoft.Extensions.Logging;

namespace JustCryptDns.DNS.DnsCrypt;

public interface IDnsCryptProxyManager : IAsyncDisposable
{
    string ExecutablePath { get; }

    bool IsInstalled { get; }

    bool IsRunning { get; }

    string? InstalledVersion { get; }

    Task<string?> DetectInstalledVersionAsync(CancellationToken cancellationToken = default);

    Task<(bool Success, string? Version, string? Error)> InstallOrUpdateAsync(
        HttpClient? httpClient = null,
        CancellationToken cancellationToken = default);

    Task<(bool Success, string? Error)> EnsureRunningAsync(
        DnsResolverEndpoint resolver,
        int internalPort,
        CancellationToken cancellationToken = default);

    Task StopAsync(CancellationToken cancellationToken = default);
}

/// <summary>
/// Manages the official <c>dnscrypt-proxy</c> binary for DNSCrypt v2 protocol support (Part 2.1).
/// Generates configuration, detects version, handles installation/updates from official releases,
/// supervises the child process, and automatically recovers from unexpected exits.
/// </summary>
public sealed class DnsCryptProxyManager : IDnsCryptProxyManager
{
    public const string LatestReleaseApiUrl = "https://api.github.com/repos/DNSCrypt/dnscrypt-proxy/releases/latest";

    private readonly IAppPaths _paths;
    private readonly ILogger<DnsCryptProxyManager> _logger;
    private readonly SemaphoreSlim _gate = new(1, 1);

    private Process? _process;
    private DnsResolverEndpoint? _activeResolver;
    private int _activePort;
    private bool _shouldBeRunning;
    private int _crashRestartCount;
    private DateTimeOffset _lastStartUtc;
    private int _disposed;

    public DnsCryptProxyManager(IAppPaths paths, ILogger<DnsCryptProxyManager> logger)
    {
        _paths = paths;
        _logger = logger;
    }

    public string SubDirectory => Path.Combine(_paths.EngineDirectory, "dnscrypt-proxy");

    public string ExecutablePath => Path.Combine(SubDirectory, "dnscrypt-proxy.exe");

    public string ConfigFilePath => Path.Combine(SubDirectory, "dnscrypt-proxy-runtime.toml");

    public bool IsInstalled => File.Exists(ExecutablePath);

    public bool IsRunning => _process is { HasExited: false };

    public string? InstalledVersion { get; private set; }

    /// <summary>
    /// Builds a minimal, self-contained <c>dnscrypt-proxy.toml</c> for the selected resolver on <paramref name="internalPort"/>.
    /// </summary>
    public static string BuildTomlConfig(DnsResolverEndpoint resolver, int internalPort)
    {
        ArgumentNullException.ThrowIfNull(resolver);
        var safeName = SanitizeTomlId(resolver.Id);
        var bootstrapHost = "1.1.1.1";
        if (IPAddress.TryParse(resolver.PrimaryIp, out var parsedPrimary))
        {
            bootstrapHost = parsedPrimary.AddressFamily == System.Net.Sockets.AddressFamily.InterNetworkV6
                ? $"[{parsedPrimary}]"
                : parsedPrimary.ToString();
        }

        var sb = new StringBuilder();
        sb.AppendLine("# Auto-generated by JustCryptDns — do not edit manually.");
        sb.AppendLine(string.Create(CultureInfo.InvariantCulture, $"listen_addresses = ['127.0.0.1:{internalPort}']"));
        sb.AppendLine("max_clients = 250");
        sb.AppendLine("ipv4_servers = true");
        sb.AppendLine("ipv6_servers = false");
        sb.AppendLine("dnscrypt_servers = true");
        sb.AppendLine("doh_servers = true");
        sb.AppendLine("require_dnssec = false");
        sb.AppendLine("require_nolog = false");
        sb.AppendLine("require_nofilter = false");
        sb.AppendLine("ignore_system_dns = true");
        sb.AppendLine(string.Create(CultureInfo.InvariantCulture, $"bootstrap_resolvers = ['{bootstrapHost}:53', '1.1.1.1:53']"));
        sb.AppendLine("netprobe_timeout = 0");
        sb.AppendLine("cache = false");

        if (resolver.Endpoint.StartsWith("sdns://", StringComparison.OrdinalIgnoreCase))
        {
            var safeStamp = SanitizeDnsStamp(resolver.Endpoint);
            sb.AppendLine(string.Create(CultureInfo.InvariantCulture, $"server_names = ['{safeName}']"));
            sb.AppendLine();
            sb.AppendLine("[static]");
            sb.AppendLine(string.Create(CultureInfo.InvariantCulture, $"  [static.'{safeName}']"));
            sb.AppendLine(string.Create(CultureInfo.InvariantCulture, $"  stamp = '{safeStamp}'"));
        }
        else
        {
            var serverName = SanitizeTomlId(resolver.Endpoint);
            sb.AppendLine(string.Create(CultureInfo.InvariantCulture, $"server_names = ['{serverName}']"));
        }

        return sb.ToString();
    }

    public async Task<string?> DetectInstalledVersionAsync(CancellationToken cancellationToken = default)
    {
        if (!IsInstalled)
        {
            InstalledVersion = null;
            return null;
        }

        try
        {
            var psi = new ProcessStartInfo(ExecutablePath, "-version")
            {
                CreateNoWindow = true,
                UseShellExecute = false,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                WorkingDirectory = SubDirectory,
            };

            using var proc = Process.Start(psi);
            if (proc is null)
            {
                return null;
            }

            var outTask = proc.StandardOutput.ReadToEndAsync(cancellationToken);
            var errTask = proc.StandardError.ReadToEndAsync(cancellationToken);
            await Task.WhenAll(outTask, errTask, proc.WaitForExitAsync(cancellationToken)).ConfigureAwait(false);
            var output = await outTask.ConfigureAwait(false);
            var version = output.Trim().Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries).FirstOrDefault()?.Trim();
            InstalledVersion = string.IsNullOrWhiteSpace(version) ? null : version;
            return InstalledVersion;
        }
        catch (Exception ex) when (ex is IOException or System.ComponentModel.Win32Exception or OperationCanceledException)
        {
            _logger.LogWarning(ex, "Failed to query dnscrypt-proxy version.");
            return null;
        }
    }

    public async Task<(bool Success, string? Version, string? Error)> InstallOrUpdateAsync(
        HttpClient? httpClient = null,
        CancellationToken cancellationToken = default)
    {
        await _gate.WaitAsync(cancellationToken).ConfigureAwait(false);
        var ownsClient = httpClient is null;
        var client = httpClient ?? new HttpClient();
        try
        {
            client.DefaultRequestHeaders.UserAgent.TryParseAdd("JustCryptDns/0.1");
            using var releaseResp = await client.GetAsync(new Uri(LatestReleaseApiUrl), cancellationToken).ConfigureAwait(false);
            if (!releaseResp.IsSuccessStatusCode)
            {
                return (false, null, $"GitHub API returned HTTP {(int)releaseResp.StatusCode}.");
            }

            await using var jsonStream = await releaseResp.Content.ReadAsStreamAsync(cancellationToken).ConfigureAwait(false);
            using var doc = await JsonDocument.ParseAsync(jsonStream, cancellationToken: cancellationToken).ConfigureAwait(false);

            string? zipUrl = null;
            if (doc.RootElement.TryGetProperty("assets", out var assets) && assets.ValueKind == JsonValueKind.Array)
            {
                foreach (var asset in assets.EnumerateArray())
                {
                    var name = asset.TryGetProperty("name", out var n) ? n.GetString() : null;
                    if (name is not null
                        && name.Contains("win64", StringComparison.OrdinalIgnoreCase)
                        && name.EndsWith(".zip", StringComparison.OrdinalIgnoreCase))
                    {
                        zipUrl = asset.TryGetProperty("browser_download_url", out var u) ? u.GetString() : null;
                        break;
                    }
                }
            }

            if (string.IsNullOrWhiteSpace(zipUrl))
            {
                return (false, null, "Could not locate win64 ZIP asset in latest dnscrypt-proxy release.");
            }

            Directory.CreateDirectory(SubDirectory);
            var tempZip = Path.Combine(SubDirectory, $"dnscrypt-proxy-{Guid.NewGuid():N}.zip");
            try
            {
                await using (var downloadStream = await client.GetStreamAsync(new Uri(zipUrl), cancellationToken).ConfigureAwait(false))
                await using (var fileStream = File.Create(tempZip))
                {
                    await downloadStream.CopyToAsync(fileStream, cancellationToken).ConfigureAwait(false);
                }

                await StopCoreAsync().ConfigureAwait(false);

                using (var archive = ZipFile.OpenRead(tempZip))
                {
                    var exeEntry = archive.Entries.FirstOrDefault(e =>
                        string.Equals(e.Name, "dnscrypt-proxy.exe", StringComparison.OrdinalIgnoreCase));
                    if (exeEntry is null)
                    {
                        return (false, null, "Downloaded archive does not contain dnscrypt-proxy.exe.");
                    }

                    exeEntry.ExtractToFile(ExecutablePath, overwrite: true);

                    var licenseEntry = archive.Entries.FirstOrDefault(e =>
                        string.Equals(e.Name, "LICENSE", StringComparison.OrdinalIgnoreCase));
                    licenseEntry?.ExtractToFile(Path.Combine(SubDirectory, "LICENSE"), overwrite: true);
                }
            }
            finally
            {
                if (File.Exists(tempZip))
                {
                    File.Delete(tempZip);
                }
            }

            var version = await DetectInstalledVersionAsync(cancellationToken).ConfigureAwait(false);
            _logger.LogInformation("Installed dnscrypt-proxy version {Version}", version);
            return (true, version, null);
        }
        catch (Exception ex) when (ex is HttpRequestException or IOException or InvalidDataException or JsonException or OperationCanceledException)
        {
            _logger.LogError(ex, "Failed to install or update dnscrypt-proxy.");
            return (false, null, ex.Message);
        }
        finally
        {
            if (ownsClient)
            {
                client.Dispose();
            }

            _gate.Release();
        }
    }

    public async Task<(bool Success, string? Error)> EnsureRunningAsync(
        DnsResolverEndpoint resolver,
        int internalPort,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(resolver);
        await _gate.WaitAsync(cancellationToken).ConfigureAwait(false);
        try
        {
            if (!IsInstalled)
            {
                return (false, $"dnscrypt-proxy.exe is not installed at '{ExecutablePath}'. Install it from DNS Manager or choose DoH/DoT.");
            }

            if (IsRunning && _activeResolver?.Id == resolver.Id && _activePort == internalPort)
            {
                return (true, null);
            }

            await StopCoreAsync().ConfigureAwait(false);
            Directory.CreateDirectory(SubDirectory);

            var toml = BuildTomlConfig(resolver, internalPort);
            await File.WriteAllTextAsync(ConfigFilePath, toml, Encoding.UTF8, cancellationToken).ConfigureAwait(false);

            var psi = new ProcessStartInfo(ExecutablePath, $"-config \"{ConfigFilePath}\"")
            {
                CreateNoWindow = true,
                UseShellExecute = false,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                WorkingDirectory = SubDirectory,
            };

            var stderrBuffer = new StringBuilder();
            var process = new Process { StartInfo = psi, EnableRaisingEvents = true };
            process.OutputDataReceived += static (_, _) => { };
            process.ErrorDataReceived += (_, args) =>
            {
                if (!string.IsNullOrEmpty(args.Data))
                {
                    lock (stderrBuffer)
                    {
                        if (stderrBuffer.Length < 4096)
                        {
                            stderrBuffer.AppendLine(args.Data);
                        }
                    }
                }
            };
            process.Exited += OnChildProcessExited;
            if (!process.Start())
            {
                process.Dispose();
                return (false, "Failed to start dnscrypt-proxy process.");
            }

            process.BeginOutputReadLine();
            process.BeginErrorReadLine();

            // Give the process a brief moment to bind or fail on configuration error.
            try
            {
                await Task.Delay(250, cancellationToken).ConfigureAwait(false);
            }
            catch (OperationCanceledException)
            {
                process.Exited -= OnChildProcessExited;
                try { if (!process.HasExited) process.Kill(entireProcessTree: true); } catch { }
                process.Dispose();
                throw;
            }

            if (process.HasExited)
            {
                string err;
                lock (stderrBuffer)
                {
                    err = stderrBuffer.ToString().Trim();
                }

                process.Dispose();
                return (false, string.IsNullOrWhiteSpace(err) ? "dnscrypt-proxy exited immediately." : err);
            }

            var nowUtc = DateTimeOffset.UtcNow;
            if (_lastStartUtc != default && (nowUtc - _lastStartUtc) > TimeSpan.FromSeconds(10))
            {
                Interlocked.Exchange(ref _crashRestartCount, 0);
            }

            _lastStartUtc = nowUtc;
            _process = process;
            _activeResolver = resolver;
            _activePort = internalPort;
            _shouldBeRunning = true;
            _logger.LogInformation("dnscrypt-proxy started for {Resolver} on 127.0.0.1:{Port}", resolver.Id, internalPort);
            return (true, null);
        }
        finally
        {
            _gate.Release();
        }
    }

    public async Task StopAsync(CancellationToken cancellationToken = default)
    {
        if (Volatile.Read(ref _disposed) != 0)
        {
            return;
        }

        await _gate.WaitAsync(cancellationToken).ConfigureAwait(false);
        try
        {
            _shouldBeRunning = false;
            Interlocked.Exchange(ref _crashRestartCount, 0);
            await StopCoreAsync().ConfigureAwait(false);
        }
        finally
        {
            _gate.Release();
        }
    }

    public async ValueTask DisposeAsync()
    {
        if (Interlocked.Exchange(ref _disposed, 1) != 0)
        {
            return;
        }

        _shouldBeRunning = false;
        await _gate.WaitAsync().ConfigureAwait(false);
        try
        {
            await StopCoreAsync().ConfigureAwait(false);
        }
        finally
        {
            _gate.Release();
            _gate.Dispose();
        }
    }

    private async Task StopCoreAsync()
    {
        var proc = _process;
        _process = null;
        if (proc is null)
        {
            return;
        }

        proc.Exited -= OnChildProcessExited;
        try
        {
            if (!proc.HasExited)
            {
                proc.Kill(entireProcessTree: true);
                using var cts = new CancellationTokenSource(TimeSpan.FromSeconds(2));
                await proc.WaitForExitAsync(cts.Token).ConfigureAwait(false);
            }
        }
        catch (Exception ex) when (ex is InvalidOperationException or System.ComponentModel.Win32Exception or OperationCanceledException)
        {
            _logger.LogDebug(ex, "Ignored error while stopping dnscrypt-proxy.");
        }
        finally
        {
            proc.Dispose();
        }
    }

    private void OnChildProcessExited(object? sender, EventArgs e)
    {
        if (!_shouldBeRunning || _activeResolver is null || Volatile.Read(ref _disposed) != 0)
        {
            return;
        }

        if (_lastStartUtc != default && (DateTimeOffset.UtcNow - _lastStartUtc) > TimeSpan.FromSeconds(10))
        {
            Interlocked.Exchange(ref _crashRestartCount, 0);
        }

        var attempt = Interlocked.Increment(ref _crashRestartCount);
        if (attempt > 3)
        {
            _logger.LogError("dnscrypt-proxy crashed {Attempt} times; automatic recovery halted.", attempt);
            return;
        }

        _logger.LogWarning("dnscrypt-proxy exited unexpectedly (attempt {Attempt}/3); scheduling recovery.", attempt);
        _ = Task.Run(async () =>
        {
            try
            {
                await Task.Delay(TimeSpan.FromMilliseconds(500 * attempt)).ConfigureAwait(false);
                if (_shouldBeRunning && Volatile.Read(ref _disposed) == 0 && _activeResolver is { } resolver)
                {
                    await EnsureRunningAsync(resolver, _activePort).ConfigureAwait(false);
                }
            }
            catch (Exception ex) when (ex is ObjectDisposedException or OperationCanceledException)
            {
            }
        });
    }

    private static string SanitizeDnsStamp(string raw)
    {
        var sb = new StringBuilder(raw.Length);
        foreach (var ch in raw)
        {
            if (!char.IsControl(ch) && ch is not '\'' and not '"' and not '\\')
            {
                sb.Append(ch);
            }
        }

        return sb.ToString();
    }

    private static string SanitizeTomlId(string raw)
    {
        var sb = new StringBuilder(raw.Length);
        foreach (var ch in raw)
        {
            if (char.IsLetterOrDigit(ch) || ch is '-' or '_' or '.')
            {
                sb.Append(ch);
            }
        }

        return sb.Length > 0 ? sb.ToString() : "default";
    }
}

/// <summary>
/// Upstream client for <see cref="DnsProtocol.DnsCrypt"/> that ensures <see cref="IDnsCryptProxyManager"/>
/// is running and forwards wire queries to its internal loopback port.
/// </summary>
public sealed class DnsCryptUpstream : IDnsUpstreamClient
{
    private readonly IDnsCryptProxyManager _manager;
    private readonly Func<int> _internalPortProvider;

    public DnsCryptUpstream(IDnsCryptProxyManager manager, Func<int> internalPortProvider)
    {
        _manager = manager;
        _internalPortProvider = internalPortProvider;
    }

    public DnsProtocol Protocol => DnsProtocol.DnsCrypt;

    public async Task<DnsQueryResult> QueryAsync(
        ReadOnlyMemory<byte> queryWire,
        DnsResolverEndpoint resolver,
        TimeSpan timeout,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(resolver);
        var internalPort = _internalPortProvider();
        var (ok, error) = await _manager.EnsureRunningAsync(resolver, internalPort, cancellationToken).ConfigureAwait(false);
        if (!ok)
        {
            return new DnsQueryResult(false, [], 0, resolver.Id, Protocol, error);
        }

        var endpoint = new IPEndPoint(IPAddress.Loopback, internalPort);
        return await UdpTcpDnsUpstream.QueryEndpointAsync(
            queryWire,
            endpoint,
            resolver.Id,
            DnsProtocol.DnsCrypt,
            timeout,
            cancellationToken).ConfigureAwait(false);
    }
}
